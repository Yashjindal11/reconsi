"""Run the ground-truth evaluation and write docs/evaluation.md.

python benchmarks/evaluate.py              # 20,000 rows x 5 seeds per scenario
python benchmarks/evaluate.py --quick      # CI smoke run, no docs written
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from reconsi import __version__
from reconsi.evaluation import SCENARIOS, run_evaluation, summarize

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "benchmarks" / "results"


def _pct(x: float) -> str:
    return "" if pd.isna(x) else f"{100 * x:.1f}%"


def render(summary: pd.DataFrame, rows: int, seeds: list[int]) -> str:
    desc = {s.name: s.description for s in SCENARIOS}
    lines = [
        "# Evaluation against known ground truth",
        "",
        "Generated by `python benchmarks/evaluate.py` with ReconSI "
        f"{__version__}: {rows:,} rows per dataset, seeds {seeds}. Each scenario injects a known "
        "corruption with `reconsi.synthetic.generate_reconciliation_pair` and checks whether "
        "ReconSI reports exactly what was injected. Precision/recall are averaged over seeds; "
        "boolean detections show the share of seeds in which the diagnosis was made.",
        "",
        "These scenarios are unambiguous by construction (each corruption touches a disjoint set "
        "of rows, keys are clean, effects are well above detection limits), so they verify "
        "correctness rather than sensitivity. Where detection gets hard (small effects, few "
        "records) is measured in [research.md](research.md).",
        "",
        "## Record-level detection",
        "",
        "| Scenario | Missing (P / R) | Extra (P / R) | Value mismatches (P / R) | Duplicate keys (P / R) | Status |",
        "|---|---|---|---|---|---|",
    ]
    for _, r in summary.iterrows():

        def pr(m: str, r: pd.Series = r) -> str:
            p, rc = r.get(f"{m}_precision"), r.get(f"{m}_recall")
            if p is None or pd.isna(p):
                return "n/a"
            return f"{_pct(p)} / {_pct(rc)}"

        lines.append(
            f"| {r['scenario']} | {pr('missing_from_right')} | {pr('missing_from_left')} | "
            f"{pr('value_mismatches')} | {pr('duplicate_keys')} | {r['statuses']} |"
        )
    lines += [
        "",
        "## Diagnoses",
        "",
        "| Scenario | Diagnosis checked | Detected |",
        "|---|---|---|",
    ]
    checks = {
        "systematic_detected": "systematic difference flagged",
        "segment_found": "concentration in the injected segment",
        "missing_segment_found": "missing records over-represent the injected segment",
        "change_points_found": "change points at both incident boundaries (+/- 1 day)",
        "timezone_hint": "constant +05:30 offset reported",
        "formatting_hint": "formatting-only string mismatches reported",
        "grain_diagnosed": "grain diagnosis: differences persist after aggregation",
    }
    for _, r in summary.iterrows():
        for key, text in checks.items():
            if key in r and not pd.isna(r[key]):
                lines.append(f"| {r['scenario']} | {text} | {_pct(r[key])} |")
    lines += ["", "## Scenarios", ""]
    lines += [f"- **{name}**: {text}" for name, text in desc.items()]
    lines += [
        "",
        "Notes: `systematic difference flagged` is expected to be 0% for `value_mismatches` "
        "(random-direction errors) and 100% for `systematic_bias_segment`. `spurious change "
        "points` (mean per run) for `incident_window`: "
        + ", ".join(
            f"{v:.2f}"
            for v in summary.get("spurious_change_points", pd.Series(dtype=float)).dropna()
        )
        + ".",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rows", type=int, default=20_000)
    parser.add_argument("--seeds", default="0,1,2,3,4")
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args()
    rows = 3_000 if args.quick else args.rows
    seeds = [0] if args.quick else [int(s) for s in args.seeds.split(",")]
    runs = run_evaluation(rows=rows, seeds=seeds)
    summary = summarize(runs)
    RESULTS.mkdir(exist_ok=True)
    name = "evaluation-quick.json" if args.quick else "evaluation.json"
    payload = {"version": __version__, "rows": rows, "seeds": seeds, "runs": runs}
    (RESULTS / name).write_text(json.dumps(payload, indent=1, default=str))
    with pd.option_context("display.width", 200, "display.max_columns", 30):
        print(summary.to_string(index=False))
    if not args.quick:
        (ROOT / "docs" / "evaluation.md").write_text(render(summary, rows, seeds))
        print("wrote docs/evaluation.md")


if __name__ == "__main__":
    main()
